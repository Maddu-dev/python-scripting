# function for addition
def add(a, b):
    return a + b

#function for subtraction
def subtraction(a, b):
    return a - b

def multiply(a, b):
    return a * b

def divide(a, b):
    return a / b

# Input values
a = 10
b = 5

print(f"Addition: {a} + {b} = {add(a,b)}")
print(f"subtraction: {a} - {b} = {subtraction(a,b)}")
print(f"multiply: {a} * {b} = {multiply(a,b)}")
print(f"Division: {a} / {b} = {divide(a,b)}")

